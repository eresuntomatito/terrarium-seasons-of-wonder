// study: The glimmerlyns and jinns failed because their breeding thresholds (energy > 1.0 and energy > 0.511
// study: respectively) allowed unlimited population growth whenever energy was sufficient, causing booms to
// study: 48 and 256 hunters that crashed under starvation when prey became scarce. Neither population
// study: responded to the scarcity signal—they bred at maximum rate until collapse. The core insight is that
// study: breeding should depend not on individual energy (which is a lagging indicator of prey abundance) but
// study: on visible population density: when many kin are nearby, stop breeding to prevent clustering that
// study: destabilizes the ecosystem. Simultaneously, when energy is low, switch to scavenging corpses and
// study: weak prey instead of active hunting, reducing predation pressure and giving the beetle population
// study: time to recover. This creates a self-regulating cycle: as hunters breed and population rises,
// study: breeding shuts down automatically; when starvation crashes the boom, low kinCount resumes breeding
// study: to slowly rebuild the population without triggering another oscillation.
function behave(me, world) {
  const generosity = me.genes[0],      // offspring energy gift
    huntFocus = me.genes[1],           // prey pursuit intensity
    seekEagerness = me.genes[2],       // attraction to fertile kin
    scavengeTendency = me.genes[3];    // scavenging behavior weight

  let x = 0, y = 0;

  // Count visible kin (not including self)
  let kinCount = 0;
  for (const o of world.others) {
    if (o.kin && Math.hypot(o.x - me.x, o.y - me.y) > 0) {
      kinCount++;
    }
  }

  // Behavior mode depends on energy level
  if (me.energy < 0.7) {
    // Scavenging mode: prioritize corpses when weak
    let target = null, bestDist = Infinity, isCorpse = false;
    for (const f of world.food) {
      const d = Math.hypot(f.x - me.x, f.y - me.y);
      if (f.corpse) {
        if (!isCorpse || d < bestDist) {
          bestDist = d;
          target = f;
          isCorpse = true;
        }
      } else if (!isCorpse && (!f.plant && f.size < me.size * 0.95)) {
        if (d < bestDist) {
          bestDist = d;
          target = f;
        }
      }
    }

    if (target) {
      x += (target.x - me.x) / (bestDist || 1);
      y += (target.y - me.y) / (bestDist || 1);
    }
  } else {
    // Active hunting mode when well-fed
    let target = null, bestDist = Infinity;
    for (const f of world.food) {
      if (f.plant || f.kin) continue;
      const d = Math.hypot(f.x - me.x, f.y - me.y);
      if (d < bestDist) {
        bestDist = d;
        target = f;
      }
    }

    if (target) {
      // Lead prey with predictive intercept
      const leadDist = Math.min(bestDist / 3.45, 7.64 + huntFocus * 14.5);
      const tx = target.x + target.vx * leadDist - me.x;
      const ty = target.y + target.vy * leadDist - me.y;
      const d = Math.hypot(tx, ty) || 1.21;
      x += tx / d * (0.551 + huntFocus * 0.407);
      y += ty / d * (0.532 + huntFocus * 0.483);
    }
  }

  // Density-dependent breeding: only breed if population is sparse (kinCount <= 5)
  // This automatically suppresses breeding when the population is crowded
  const populationSparse = kinCount <= 5;
  const readyToBreed = me.fertile && me.energy > 1.05 && populationSparse;

  // Kin interaction: seek mates when breeding, maintain territory otherwise
  for (const o of world.others) {
    if (!o.kin) continue;
    const d = Math.hypot(o.x - me.x, o.y - me.y);
    if (d === 0) continue;

    if (readyToBreed && o.willing) {
      // Seek willing mates for free pair-mating
      const strength = 0.594 + seekEagerness * 0.402;
      x += (o.x - me.x) / d * strength;
      y += (o.y - me.y) / d * strength;
    } else if (d < 47.7) {
      // Repel kin to maintain hunting territory
      // Reduce repulsion when very weak to allow cooperative grouping
      const repulsion = me.energy < 0.5 ? 0.2 : (me.energy < 0.8 ? 0.4 : 0.686);
      x -= (o.x - me.x) / d * repulsion;
      y -= (o.y - me.y) / d * repulsion;
    }
  }

  // Wandering when no clear target
  if (me.energy >= 0.7) {
    let hasTarget = false;
    for (const f of world.food) {
      if (!f.plant && !f.kin && f.size < me.size * 0.95) {
        hasTarget = true;
        break;
      }
    }
    if (!hasTarget) {
      const angle = world.noise(me.x * 0.501, me.y * 0.472) * Math.PI * 4.02;
      x += Math.cos(angle) * (0.192 + scavengeTendency * 0.263);
      y += Math.sin(angle) * (0.214 + scavengeTendency * 0.301);
    }
  }

  return {
    x,
    y,
    mate: readyToBreed,
    give: 0.15 + generosity * 0.266,
    signal: readyToBreed ? 0.375 : 0
  };
}
