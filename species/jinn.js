// study: The mystic2s succeeded by establishing a reachable breeding threshold (energy > 0.511) and actively
// study: attracting kin with signal when fertile, enabling pair-mating at no energy cost. Yet their
// study: population of 6 saw 8 starve in the end—they bred too eagerly and outpaced food supply. Earlier
// study: hunters failed catastrophically: galacticraptors repelled kin (impossible to mate), geneticgadgets
// study: clustered for mating and starved together, and pulses had impossible thresholds (energy > 2 when max
// study: is 2). The pattern is clear: breeding threshold must be reachable and selective, kin attraction must
// study: enable meeting without clustering, and energy cost to offspring must fit the hunting reality. With
// study: corpses (15% after kill) and beetles (size ~2.5) now available, a hunter can scavenge between hunts
// study: and exploit this safety margin. A more conservative breeder—higher threshold (~1.25), corpse-first
// study: strategy when weak, beetle targeting—can reduce overpopulation while still rebuilding population
// study: when prey truly booms, avoiding the feast-famine oscillation that killed mystic2s.
function behave(me, world) {
  const vigor = me.genes[0];      // Hunting drive and prey interception
  const affinity = me.genes[1];   // Attraction strength to willing mates
  const generosity = me.genes[2]; // Energy fraction given to offspring
  const caution = me.genes[3];    // Predator avoidance intensity

  // Identify food by type with separate tracking
  let corpse = null, bestCorpseD = Infinity;
  let beetle = null, bestBeetleD = Infinity;
  let livePrey = null, bestLiveD = Infinity;

  for (const f of world.food) {
    if (f.plant || (f.kin && me.energy > 0.5)) continue;

    const d = Math.hypot(f.x - me.x, f.y - me.y);

    if (f.corpse && d < bestCorpseD) {
      corpse = f;
      bestCorpseD = d;
    }
    if (f.size > 2.1 && f.size < 2.9 && d < bestBeetleD) {
      beetle = f;
      bestBeetleD = d;
    }
    if (!f.corpse && d < bestLiveD) {
      livePrey = f;
      bestLiveD = d;
    }
  }

  // Priority: corpse when desperate, beetles for steady food, live prey for growth
  let target = null;
  if (me.energy < 1.15 && corpse && bestCorpseD < 75) {
    target = corpse;
  } else if (beetle && bestBeetleD < 60) {
    target = beetle;
  } else if (livePrey && bestLiveD < 65) {
    target = livePrey;
  }

  let x = 0, y = 0;

  if (target) {
    const d = Math.hypot(target.x - me.x, target.y - me.y) || 1;
    let tx = target.x - me.x;
    let ty = target.y - me.y;

    // Lead moving targets (live prey and beetles, not corpses)
    if (target !== corpse && target.vx !== undefined) {
      const intercept = Math.min(d / 2.6, 7 + vigor * 14);
      tx += target.vx * intercept;
      ty += target.vy * intercept;
    }

    const dist = Math.hypot(tx, ty) || 1;
    x += tx / dist * (0.68 + vigor * 0.32);
    y += ty / dist * (0.68 + vigor * 0.32);
  } else {
    // Exploration via perlin noise when no target
    const noiseVal = world.noise(me.x * 0.26, me.y * 0.26);
    const angle = noiseVal * Math.PI * 3.7;
    x += Math.cos(angle) * 0.45;
    y += Math.sin(angle) * 0.40;
  }

  // Kin interactions: mate when ready, maintain territory otherwise
  for (const o of world.others) {
    const d = Math.hypot(o.x - me.x, o.y - me.y);
    if (d === 0) continue;

    if (!o.kin) {
      // Flee from predators
      const fearDist = 20 + caution * 30;
      if (o.size >= me.size * 1.17 && d < fearDist) {
        x -= (o.x - me.x) / d * (1.28 + caution * 0.72);
        y -= (o.y - me.y) / d * (1.28 + caution * 0.72);
      }
    } else {
      // Seek willing mates when fertile and well-fed
      if (me.fertile && me.energy > 1.25 && o.willing && d < 52) {
        x += (o.x - me.x) / d * (0.64 + affinity * 0.36);
        y += (o.y - me.y) / d * (0.64 + affinity * 0.36);
      } else if (d < 30) {
        // Maintain territory when not breeding
        x -= (o.x - me.x) / d * 0.15;
        y -= (o.y - me.y) / d * 0.15;
      }
    }
  }

  // Conservative breeding: only when food is clearly abundant
  const foodCount = world.food.filter(f => !f.plant).length;
  const shouldBreed = me.fertile && me.energy > 1.24 && foodCount > 3.2;

  return {
    x, y,
    mate: shouldBreed,
    give: 0.095 + generosity * 0.345,
    signal: shouldBreed ? 0.76 : 0,
    eat: true
  };
}
