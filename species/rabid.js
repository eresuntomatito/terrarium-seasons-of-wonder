function behave(me, world) {
  const generosity = me.genes[0],
    huntFocus = me.genes[1],
    territoriality = me.genes[2],
    restlessness = me.genes[3];

  // Track breeding cooldown to space births
  if (!me.memory.lastBreedFrame) {
    me.memory.lastBreedFrame = -100;
  }

  let x = 0, y = 0;

  // Find hunting and scavenging targets
  let corpseTarget = null, bestCorpseDist = Infinity;
  let huntTarget = null, bestHuntDist = Infinity;
  let visibleFood = 0;
  let kinCount = 0;

  for (const f of world.food) {
    if (f.corpse) {
      visibleFood++;
      const d = Math.hypot(f.x - me.x, f.y - me.y);
      if (d < bestCorpseDist) {
        bestCorpseDist = d;
        corpseTarget = f;
      }
    } else if (!f.kin) {
      visibleFood++;
      const d = Math.hypot(f.x - me.x, f.y - me.y);
      if (d < bestHuntDist) {
        bestHuntDist = d;
        huntTarget = f;
      }
    }
  }

  for (const o of world.others) {
    if (o.kin && Math.hypot(o.x - me.x, o.y - me.y) < 70) {
      kinCount++;
    }
  }

  // Target selection: corpses when weak, living prey otherwise
  let target = null;
  if (me.energy < 0.65 && corpseTarget) {
    target = corpseTarget;
  } else if (huntTarget) {
    target = huntTarget;
  } else if (corpseTarget && me.energy < 0.95) {
    target = corpseTarget;
  }

  if (target) {
    const d = Math.hypot(target.x - me.x, target.y - me.y) || 1;
    if (target.corpse) {
      x += (target.x - me.x) / d * 0.85;
      y += (target.y - me.y) / d * 0.85;
    } else {
      const lead = Math.min(bestHuntDist / 3.5, 8 + huntFocus * 15);
      const tx = target.x + (target.vx || 0) * lead;
      const ty = target.y + (target.vy || 0) * lead;
      const td = Math.hypot(tx - me.x, ty - me.y) || 1;
      x += (tx - me.x) / td * (0.55 + huntFocus * 0.4);
      y += (ty - me.y) / td * (0.55 + huntFocus * 0.4);
    }
  } else {
    const angle = world.noise(me.x * 0.5, me.y * 0.47) * Math.PI * 4;
    x += Math.cos(angle) * 0.32;
    y += Math.sin(angle) * 0.28;
  }

  // Extremely conservative breeding: high energy, abundant food, and mostly alone
  const canBreedAgain = world.t - me.memory.lastBreedFrame > 20;
  const hasAbundantFood = visibleFood > 18;
  const isAlmostAlone = kinCount <= 1;
  const shouldBreed = me.fertile
    && me.energy > 1.75
    && hasAbundantFood
    && isAlmostAlone
    && canBreedAgain;

  if (shouldBreed) {
    me.memory.lastBreedFrame = world.t;
  }

  // Strong territorial behavior: repel kin to keep prey spread, attract only willing mates
  for (const o of world.others) {
    if (!o.kin) continue;
    const d = Math.hypot(o.x - me.x, o.y - me.y);
    if (d === 0) continue;

    if (shouldBreed && o.willing) {
      const attractStrength = 0.65 + territoriality * 0.35;
      x += (o.x - me.x) / d * attractStrength;
      y += (o.y - me.y) / d * attractStrength;
    } else if (d < 70) {
      const repulsion = 0.75 + territoriality * 0.5;
      x -= (o.x - me.x) / d * repulsion;
      y -= (o.y - me.y) / d * repulsion;
    }
  }

  return {
    x,
    y,
    mate: shouldBreed,
    give: 0.11 + generosity * 0.14,
    signal: shouldBreed ? 0.7 : 0
  };
}
